"""
Calculate APC ellipsoidal height.

Principle:

In general, the position of APC is higher than ARP , which is higher than the marker. The relationship between them is as follows:
h_marker < h_ARP < h_APC

(1) firstly to calculate the ARP height.
Nevada Geodetic Laboratory (UNR) provides "tenv3", which contains the station's geodetic height information. Following this purpose, column 23 supplies h_marker and column 14 supplies the vertical marker-to-ARP offset.
h_ARP = h_marker + h_marker-to-ARP offset

(2) then to calculate the APC height.
The Phase Center Offset (PCO) is the vertical distance from the ARP to the Antenna Phase Center (APC).

The PCO.txt file is generated by the output of PCO_extraction.py, which contains the PCO values for each station and frequency.
h_APC = h_ARP + PCO_UP_m

So finally,
h_APC = h_marker + h_marker-to-ARP offset + PCO_UP_m.

Example:
    python GNSS-IR-geodetic-height.py --date 2024 274 --station ISLK -fr 1

    1. fetch tenv3 text directly from the station's UNR IGS20 URL:
    https://geodesy.unr.edu/gps_timeseries/IGS20/tenv3/IGS20/{STATION}.tenv3

    2. Read Phase Center correction value from --pco-file, which defaults to intermediate_files/PCO_APC/PCO.txt from PCO_extraction.py.

    3. GPS frequency numbers are converted to ANTEX codes internally, e.g.
       1 -> G01 (GPS L1), 2 -> G02 (GPS L2), and 5 -> G05 (GPS L5).

By default results are written to intermediate_files/PCO_APC/APC_geodetic_height.txt; use --output for a station-day path.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from datetime import date, timedelta
from pathlib import Path
from urllib.error import URLError
from urllib.request import urlopen

HERE = Path(__file__).resolve().parent
PCO_APC_DIR = HERE / "intermediate_files" / "PCO_APC"
MONTHS = "JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC".split()
OUTPUT_FILE = PCO_APC_DIR / "APC_geodetic_height.txt"


def year_doy(values: list[str]) -> date:
    """Convert a year and day-of-year pair (for example, 2024 001) to a date."""
    try:
        year, doy = map(int, values)
        day = date(year, 1, 1) + timedelta(days=doy - 1)
    except (TypeError, ValueError, OverflowError) as exc:
        raise argparse.ArgumentTypeError("date must be YEAR DOY, e.g. 2024 001") from exc
    if doy < 1 or day.year != year:
        raise argparse.ArgumentTypeError(f"invalid day of year {doy} for {year}")
    return day


def gps_frequency(value: str) -> str:
    """Convert a GPS frequency number to its three-character ANTEX code."""
    try:
        frequency = int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("frequency must be a number, e.g. 1") from exc
    if frequency not in {1, 2, 5}:
        raise argparse.ArgumentTypeError("GPS frequency must be 1, 2, or 5")
    return f"G{frequency:02d}"


def number(value: str, field: str) -> float:
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{field} must be finite, got {value!r}")
    return result


def read_daily_tenv3(text: str, station: str, day: date) -> tuple[float, float]:
    """Match station and exact MJD, cross-checking the date without system locale."""
    mjd = (day - date(1858, 11, 17)).days
    tag = f"{day.year % 100:02d}{MONTHS[day.month - 1]}{day.day:02d}"
    matches = []
    for line in text.splitlines():
        fields = line.split()
        if not fields or fields[0].upper() != station:
            continue
        if len(fields) < 4:
            raise ValueError("Malformed tenv3 row")
        if fields[1].upper() != tag and fields[3] != str(mjd):
            continue
        if fields[1].upper() != tag or int(fields[3]) != mjd:
            raise ValueError("tenv3 date and MJD disagree")
        if len(fields) != 23:
            raise ValueError(f"Expected 23 tenv3 columns, found {len(fields)}")
        matches.append((number(fields[22], "h_marker"), number(fields[13], "antenna height")))
    if len(matches) != 1:
        raise ValueError(f"Expected one tenv3 row for {station} {day}; found {len(matches)}")
    return matches[0]


def fetch_tenv3(station: str) -> tuple[str, str]:
    """Fetch station data directly over HTTPS without reading or saving a file."""
    url = f"https://geodesy.unr.edu/gps_timeseries/IGS20/tenv3/IGS20/{station}.tenv3"
    with urlopen(url, timeout=60) as response:
        return response.read().decode("ascii"), url


def read_pco(path: Path, station: str, frequency: str) -> tuple[str, str, float]:
    """Select a unique station/frequency row from the user-confirmed PCO table."""
    lines = [line.split() for line in path.read_text(encoding="utf-8-sig").splitlines()
             if line.strip() and not line.lstrip().startswith("#")]
    required = {"station", "antenna_type", "radome", "frequency", "PCO_UP_m"}
    if not lines or not required.issubset(lines[0]) or len(set(lines[0])) != len(lines[0]):
        raise ValueError(f"PCO table requires unique columns: {sorted(required)}")
    matches, available = [], []
    for fields in lines[1:]:
        if len(fields) != len(lines[0]):
            raise ValueError("PCO table row has an incorrect number of columns")
        row = dict(zip(lines[0], fields))
        key = tuple(row[k].upper() for k in ("station", "antenna_type", "radome", "frequency"))
        if key[0] == station:
            available.append("/".join(key[1:]))
        if (key[0], key[3]) == (station, frequency):
            if not key[1] or not key[2]:
                raise ValueError("PCO row must specify antenna type and radome")
            up = number(row["PCO_UP_m"], "PCO_UP_m")
            if "PCO_UP_mm" in row and not math.isclose(
                    up * 1000, number(row["PCO_UP_mm"], "PCO_UP_mm"), abs_tol=0.00001):
                raise ValueError("PCO_UP_m and PCO_UP_mm are inconsistent")
            matches.append((key[1], key[2], up))
    if len(matches) != 1:
        raise ValueError(f"Expected one PCO for {station}/{frequency}; "
                         f"found {len(matches)}. Available for station: {available}")
    return matches[0]


def calculate(day: date, station: str, frequency: str, *,
              pco_file: Path = PCO_APC_DIR / "PCO.txt") -> dict:
    station, frequency = station.strip().upper(), frequency.strip().upper()
    if not re.fullmatch(r"[A-Z0-9]{4}", station):
        raise ValueError("Station must be a four-character UNR station ID")
    if not re.fullmatch(r"[GRECJSI][0-9]{2}", frequency):
        raise ValueError("Use an ANTEX constellation/frequency code, e.g. G01 (GPS L1), not L1")
    model, radome, pco = read_pco(pco_file, station, frequency)
    text, tenv3_source = fetch_tenv3(station)
    marker, delta = read_daily_tenv3(text, station, day)
    arp = marker + delta
    return {"date": f"{day.year} {day.timetuple().tm_yday:03d}",
            "station": station, "frequency": frequency,
            "antenna_type": model, "radome": radome,
            "h_marker_m": marker, "marker_to_ARP_up_m": delta,
            "h_ARP_m": arp, "PCO_UP_m": pco, "h_APC_m": arp + pco,
            "tenv3_source": tenv3_source,
            "pco_source": str(pco_file.resolve())}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--date", required=True, nargs=2, metavar=("YEAR", "DOY"),
                        help="year and day of year, e.g. 2024 001")
    parser.add_argument("--station", required=True, help="Four-character station ID, e.g. ISLK")
    parser.add_argument("-fr", required=True, type=gps_frequency,
                        help="GPS frequency number: 1, 2, or 5")
    parser.add_argument("--pco-file", type=Path, default=PCO_APC_DIR / "PCO.txt",
                        help="PCO table path (default: intermediate_files/PCO_APC/PCO.txt)")
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    parser.add_argument("--output", type=Path, help="Override APC output path")
    args = parser.parse_args(argv)
    try:
        day = year_doy(args.date)
        result = calculate(day, args.station, args.fr,
                           pco_file=args.pco_file)
    except (OSError, ValueError, URLError, EOFError) as exc:
        parser.exit(1, f"Error: {exc}\n")
    if args.json:
        output = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    else:
        output = "\n".join(
            f"{key}: {value:.6f}" if isinstance(value, float) else f"{key}: {value}"
            for key, value in result.items()
        ) + "\n"
    output_file = args.output or OUTPUT_FILE
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(output, encoding="utf-8")
    print(f"Result written to {output_file}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
